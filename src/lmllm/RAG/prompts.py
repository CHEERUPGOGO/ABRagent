def get_prompt_summary() -> str:
    """生成所有 Prompt 的汇总文本,用于界面展示和审计."""
    lines = ["## 系统 Prompt 留痕"]
    for name, prompt in PROMPT_REGISTRY.items():
        lines.append(f"### {name}")
        lines.append("```text")
        lines.append(prompt.strip())
        lines.append("```")
        lines.append("")
    return "\n".join(lines)